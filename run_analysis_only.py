#!/usr/bin/env python3
"""Reproduce the public analysis layer without running docking.

The default ``summary-only`` mode uses only the compact CSV/JSON tables that
are suitable for publication.  ``--mode full`` retains the original Step 6A
entry point and requires the local pose files generated by the full workflow.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


ROOT = Path(__file__).resolve().parent


def summary_only(output_dir: Path) -> dict:
    """Rebuild compact score, orientation, and H3 summaries from public tables."""
    score = pd.read_csv(ROOT / "results" / "receptor_ensemble" / "score_matrix.csv")
    orientation = pd.read_csv(ROOT / "results" / "orientation_robustness" / "multi_seed_top_poses.csv")
    h3 = pd.read_csv(ROOT / "results" / "final_analysis" / "h3_contact_summary.csv")
    h3_residue = pd.read_csv(ROOT / "results" / "final_analysis" / "h3_residue_contact_comparison.csv")

    output_dir.mkdir(parents=True, exist_ok=True)

    score_long = score.melt(
        id_vars=["compound_id", "cluster_id", "row_index", "group"],
        value_vars=["score_2AM9", "score_2AMA"],
        var_name="receptor",
        value_name="vina_score_kcal_mol",
    )
    score_summary = (
        score_long.groupby(["receptor", "cluster_id"], as_index=False)["vina_score_kcal_mol"]
        .agg(["count", "mean", "median", "min", "max", "std"])
        .reset_index()
    )
    score_summary.to_csv(output_dir / "score_summary.csv", index=False)

    orientation_summary = (
        orientation.groupby(["compound_id", "row_index", "orientation_class"], as_index=False)
        .agg(
            n_seed_runs=("seed", "count"),
            mean_vina_score_kcal_mol=("vina_score_kcal_mol", "mean"),
            mean_core_best_fit_rmsd_TES_A=("core_best_fit_rmsd_TES_A", "mean"),
        )
    )
    orientation_summary.to_csv(output_dir / "orientation_summary.csv", index=False)

    h3_summary = (
        h3.groupby(["receptor", "region"], as_index=False)
        .agg(
            compound_count=("compound_id", "nunique"),
            run_count=("n_runs", "sum"),
            mean_distance_A=("mean_distance_A", "mean"),
            fraction_lt_2_5_A=("fraction_lt_2_5_A", "mean"),
        )
    )
    h3_summary.to_csv(output_dir / "h3_summary.csv", index=False)
    h3_residue.to_csv(output_dir / "h3_residue_contacts.csv", index=False)

    plt.figure(figsize=(7.2, 4.6))
    for receptor, group in score_long.groupby("receptor"):
        plt.scatter(group["cluster_id"], group["vina_score_kcal_mol"], label=receptor, alpha=0.8)
    plt.xlabel("Cluster")
    plt.ylabel("Top-pose Vina score (kcal/mol)")
    plt.title("Public score summary")
    plt.legend(frameon=False)
    plt.tight_layout()
    plt.savefig(output_dir / "score_summary.png", dpi=200)
    plt.close()

    orientation_counts = (
        orientation.groupby(["row_index", "orientation_class"], as_index=False)
        .size()
        .pivot(index="row_index", columns="orientation_class", values="size")
        .fillna(0)
    )
    orientation_counts.plot(kind="bar", stacked=True, figsize=(8.2, 4.8), colormap="Set2")
    plt.xlabel("Compound row index")
    plt.ylabel("Number of seed runs")
    plt.title("Public orientation stability summary")
    plt.tight_layout()
    plt.savefig(output_dir / "orientation_summary.png", dpi=200)
    plt.close()

    h3_plot = h3.groupby(["receptor", "region"], as_index=False)["mean_distance_A"].mean()
    h3_pivot = h3_plot.pivot(index="region", columns="receptor", values="mean_distance_A")
    h3_pivot.plot(kind="bar", figsize=(8.2, 4.8))
    plt.ylabel("Mean minimum distance (Å)")
    plt.xlabel("C17 local region")
    plt.title("Public H3 local-contact summary")
    plt.xticks(rotation=30, ha="right")
    plt.tight_layout()
    plt.savefig(output_dir / "h3_summary.png", dpi=200)
    plt.close()

    validation = {
        "status": "pass",
        "mode": "summary-only",
        "score_rows": int(len(score)),
        "orientation_rows": int(len(orientation)),
        "h3_rows": int(len(h3)),
        "h3_residue_rows": int(len(h3_residue)),
        "source_tables": [
            "results/receptor_ensemble/score_matrix.csv",
            "results/orientation_robustness/multi_seed_top_poses.csv",
            "results/final_analysis/h3_contact_summary.csv",
            "results/final_analysis/h3_residue_contact_comparison.csv",
        ],
    }
    (output_dir / "summary_only_validation.json").write_text(
        json.dumps(validation, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    return validation


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["summary-only", "full"], default="summary-only")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "results" / "summary_only")
    args = parser.parse_args()

    if args.mode == "summary-only":
        print(json.dumps(summary_only(args.output_dir), indent=2, ensure_ascii=False))
        return

    import runpy

    script = ROOT / "scripts" / "21_h3_local_packing_validation.py"
    if not script.exists():
        raise FileNotFoundError(f"Required analysis script is missing: {script}")
    runpy.run_path(str(script), run_name="__main__")


if __name__ == "__main__":
    main()
